// FACTOR FIND — briefing cards (intro before the first round, and the
// "?" popup during play). Exposes FF.tutorial.
(function (global) {
  'use strict';
  const FF = global.FF = global.FF || {};

  const CARDS = [
    { title: 'THE DATA', c: '#B87613',
      body: 'A sample of <b>150 to 500 people</b> answered 4–9 questionnaire items, generated by a <b>hidden factor model</b>. ' +
        'The left side shows their correlations four ways: a <b>scree plot</b>, a <b>heatmap</b>, a <b>correlation network</b> and a ' +
        '<b>partial correlation network</b> (<span class="pos">blue</span> = positive, <span class="neg">red</span> = negative, stronger = darker and thicker).' },
    { title: 'DRAW A MODEL', c: '#2B2F36',
      body: 'Items are the numbered squares. <b>Double-click</b> the canvas to add a factor, then <b>click the items it measures</b> and press OK. ' +
        '(Shortcut: select items first, then double-click.) Double-click a factor to change its items. <b>Loading</b> draws single factor → item arrows; ' +
        '<b>Correlate</b> links the residuals of two items (the small circles under them) or two factors. New factors start out correlated with the others: ' +
        '<b>Erase</b> the curved arrow to make them independent. Keys: <span class="k">V</span> <span class="k">F</span> <span class="k">A</span> <span class="k">C</span> <span class="k">E</span> tools, <span class="k">T</span> tidy, <span class="k">⌘/Ctrl Z</span> undo.' },
    { title: 'ONE FIT', c: '#2E8B57',
      body: 'You get <b>one FIT</b> per dataset, estimated by maximum likelihood as in lavaan. If the model cannot be estimated ' +
        '(not identified, no convergence, or a Heywood case such as a negative variance) you get an error and can fix it for free. ' +
        'Afterwards, compare the <b>model-implied</b> correlations and the <b>residuals</b> with the data.' },
    { title: 'SCORING', c: '#79808C',
      body: '<b>Fit (40):</b> the χ² test, RMSEA, CFI and SRMR each give 10 points for good fit and 5 for acceptable fit. ' +
        'A saturated model (df = 0) gets no fit points. <b>Parsimony (60):</b> your BIC is compared with the BIC of the true model on the same data; ' +
        'every BIC point above it costs 3 points. Good fit is easy to get by adding paths. Finding the true model is not.' },
  ];

  let onDone = null;

  function show(opts) {
    opts = opts || {};
    const scr = document.getElementById('screen-tutorial');
    const grid = document.getElementById('tut-cards');
    const btn = document.getElementById('tut-continue');
    grid.innerHTML = '';
    CARDS.forEach((c, k) => {
      const d = document.createElement('div');
      d.className = 'tut-card';
      d.style.setProperty('--c', c.c);
      d.style.animationDelay = (opts.popup ? 0 : 0.12 * k) + 's';
      d.innerHTML = '<h3>' + c.title + '</h3><p>' + c.body + '</p>';
      grid.appendChild(d);
    });
    btn.textContent = opts.popup ? 'BACK TO THE GAME' : 'START';
    scr.classList.toggle('popup', !!opts.popup);
    scr.classList.add('show');
    onDone = opts.onDismiss || null;
  }
  function hide() {
    document.getElementById('screen-tutorial').classList.remove('show', 'popup');
    const f = onDone; onDone = null;
    if (f) f();
  }
  function isOpen() { return document.getElementById('screen-tutorial').classList.contains('show'); }

  document.getElementById('tut-continue').addEventListener('click', () => {
    if (global.GaltonAudio) global.GaltonAudio.SFX.click();
    hide();
  });
  document.getElementById('tut-close').addEventListener('click', hide);

  FF.tutorial = { show, hide, isOpen };
})(window);
