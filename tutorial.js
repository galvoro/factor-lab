// FACTOR FIND — briefing cards (intro before the first round, and the
// "?" popup during play). Exposes FF.tutorial.
(function (global) {
  'use strict';
  const FF = global.FF = global.FF || {};

  const CARDS = [
    { title: 'THE DATA', c: '#B87613',
      body: 'Each round, <b>200 people</b> answered 4–9 questionnaire items. Their answers were generated by a <b>hidden factor model</b>. ' +
        'The left side shows the correlations four ways: a <b>scree plot</b>, a <b>heatmap</b>, a <b>correlation network</b> and a ' +
        '<b>partial correlation network</b> (<span class="pos">blue</span> = positive, <span class="neg">red</span> = negative, stronger = darker and thicker).' },
    { title: 'DRAW A MODEL', c: '#2B2F36',
      body: 'Items are the numbered squares. <b>Click items</b> to select them, then press <b>+ Factor</b> to give them a common factor. ' +
        'Use <b>Loading</b> to draw more arrows (factor → item) and <b>Correlate</b> for a residual correlation between two items. ' +
        'New factors start out correlated with the others: <b>Erase</b> the curved arrow to make them independent. Drag anything to rearrange it. ' +
        'Keys: <span class="k">V</span> <span class="k">F</span> <span class="k">A</span> <span class="k">C</span> <span class="k">E</span> tools, <span class="k">T</span> tidy, <span class="k">⌘/Ctrl Z</span> undo.' },
    { title: 'FIT', c: '#2E8B57',
      body: 'Press <b>FIT</b> to estimate your model by maximum likelihood, as lavaan does. Paths turn <span class="pos">blue</span> or ' +
        '<span class="neg">red</span> and their width shows the standardized estimate. Switch the left side to <b>Model</b> to see the ' +
        'correlations your model implies, or to <b>Residuals</b> to see what it still gets wrong.' },
    { title: 'SCORING', c: '#79808C',
      body: '<b>RMSEA &lt; .05</b> earns 10 points, <b>&lt; .08</b> earns 5. A saturated model (df = 0) or an improper solution earns 0. ' +
        'When you <b>lock in</b>, the true model is revealed: a <b>BIC</b> within 2 of the truth’s (or lower) adds 10 parsimony points, within 10 adds 5. ' +
        'You get <b>3 fits</b> per round and each revision costs 2 points. Five rounds, getting harder.' },
  ];

  let onDone = null;

  function show(opts) {
    opts = opts || {};
    const scr = document.getElementById('screen-tutorial');
    const grid = document.getElementById('tut-cards');
    const btn = document.getElementById('tut-continue');
    grid.innerHTML = '';
    CARDS.forEach((c, k) => {
      const d = document.createElement('div');
      d.className = 'tut-card';
      d.style.setProperty('--c', c.c);
      d.style.animationDelay = (opts.popup ? 0 : 0.12 * k) + 's';
      d.innerHTML = '<h3>' + c.title + '</h3><p>' + c.body + '</p>';
      grid.appendChild(d);
    });
    btn.textContent = opts.popup ? 'BACK TO THE GAME' : 'START';
    scr.classList.toggle('popup', !!opts.popup);
    scr.classList.add('show');
    onDone = opts.onDismiss || null;
  }
  function hide() {
    document.getElementById('screen-tutorial').classList.remove('show', 'popup');
    const f = onDone; onDone = null;
    if (f) f();
  }
  function isOpen() { return document.getElementById('screen-tutorial').classList.contains('show'); }

  document.getElementById('tut-continue').addEventListener('click', () => {
    if (global.GaltonAudio) global.GaltonAudio.SFX.click();
    hide();
  });
  document.getElementById('tut-close').addEventListener('click', hide);

  FF.tutorial = { show, hide, isOpen };
})(window);
